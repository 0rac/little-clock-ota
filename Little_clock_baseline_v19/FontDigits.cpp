// ============================================================
// DIGIT GLYPH SELECTOR
// ============================================================
const uint8_t* getDigitGlyph(uint8_t d)
{
  if (d > 15) d = 0;

  switch (currentFont)
  {
    case FONT_BOLD:
      return boldDigits[d];

    case FONT_BLOCKY:
    default:
      return blockyDigits[d];
  }
}

// ============================================================
// PROPORTIONAL ADVANCE PER FONT
// Glyph width is 6 columns. Advance of 7 adds 1px spacing.
// Both fonts currently use the same advance — adjust here if
// a future font needs different spacing.
// ============================================================
uint8_t getFontAdvance(FontStyle font)
{
  (void)font;   // suppress unused warning — both fonts use 7 for now
  return 7;
}
